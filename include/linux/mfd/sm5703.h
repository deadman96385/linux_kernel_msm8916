#ifndef __LINUX_MFD_SM5703_H
#define __LINUX_MFD_SM5703_H

#include <linux/bits.h>
#include <linux/mutex.h>

struct device;
struct gpio_desc;
struct regmap;
struct regmap_irq_chip_data;

struct sm5703 {
	struct device *dev;
	struct regmap *regmap;
	struct regmap_irq_chip_data *irq_data;
	struct gpio_desc *reset_gpio;
	/* Protects charge_requested, otg_enabled and the shared mode register. */
	struct mutex mode_lock;
	bool charge_requested;
	bool otg_enabled;
};

enum sm5703_irq {
	SM5703_IRQ_AICL,
	SM5703_IRQ_BATOVP,
	SM5703_IRQ_LOWBAT,
	SM5703_IRQ_VBUSLIMIT,
	SM5703_IRQ_DISLIMIT,
	SM5703_IRQ_VSYSOLP,
	SM5703_IRQ_OTGFAIL,
	SM5703_IRQ_THERMREG,
	SM5703_IRQ_THERMSHDN,
	SM5703_IRQ_VSYSNG,
	SM5703_IRQ_VSYSOK,
	SM5703_IRQ_NOBAT,
	SM5703_IRQ_PRETMROFF,
	SM5703_IRQ_FASTTMROFF,
	SM5703_IRQ_CHGON,
	SM5703_IRQ_Q4FULLON,
	SM5703_IRQ_TOPOFF,
	SM5703_IRQ_DONE,
	SM5703_IRQ_CHGRSTF,
	SM5703_IRQ_FLEDSHORT,
	SM5703_IRQ_FLEDOPEN,
	SM5703_IRQ_BOOSTPOK_NG,
	SM5703_IRQ_BOOSTPOK,
	SM5703_IRQ_ABSTMRON,
	SM5703_IRQ_MAX,
};

/* Main charger/PMIC register bank at I2C address 0x49. */
#define SM5703_REG_INT1			0x00
#define SM5703_REG_INT2			0x01
#define SM5703_REG_INT3			0x02
#define SM5703_REG_INT4			0x03
#define SM5703_REG_INTMSK1		0x04
#define SM5703_REG_INTMSK2		0x05
#define SM5703_REG_INTMSK3		0x06
#define SM5703_REG_INTMSK4		0x07
#define SM5703_REG_STATUS1		0x08
#define SM5703_REG_STATUS2		0x09
#define SM5703_REG_STATUS3		0x0a
#define SM5703_REG_STATUS4		0x0b
#define SM5703_REG_CNTL			0x0c
#define SM5703_REG_VBUSCNTL		0x0d
#define SM5703_REG_CHGCNTL1		0x0e
#define SM5703_REG_CHGCNTL2		0x0f
#define SM5703_REG_CHGCNTL3		0x10
#define SM5703_REG_CHGCNTL4		0x11
#define SM5703_REG_CHGCNTL5		0x12
#define SM5703_REG_CHGCNTL6		0x13
#define SM5703_REG_FLEDCNTL6		0x19
#define SM5703_REG_LDO1			0x1a
#define SM5703_REG_LDO2			0x1b
#define SM5703_REG_LDO3			0x1c
#define SM5703_REG_BUCK			0x1d
#define SM5703_REG_DEVICE_ID		0x1e
#define SM5703_REG_OTGCURRENTCNTL	0x60
#define SM5703_REG_Q3LIMITCNTL		0x66
#define SM5703_REG_STATUS5		0x6b

#define SM5703_CNTL_OPERATION_MODE_MASK	GENMASK(2, 0)
#define SM5703_CNTL_CHARGING_OFF	0x04
#define SM5703_CNTL_CHARGING_ON		0x05
#define SM5703_CNTL_FLASH_BOOST		0x06
#define SM5703_CNTL_USB_OTG		0x07
#define SM5703_CNTL_AUTOSET		BIT(4)
#define SM5703_CNTL_USBLDO1_EN		BIT(6)
#define SM5703_CNTL_USBLDO2_EN		BIT(7)

#define SM5703_FLEDCNTL6_BSTOUT_MASK	GENMASK(3, 0)
#define SM5703_FLEDCNTL6_BSTOUT_4P5V	0x05
#define SM5703_FLEDCNTL6_BSTOUT_5P0V	0x0a

#define SM5703_STATUS1_AICL		BIT(0)
#define SM5703_STATUS1_OTGFAIL		BIT(7)
#define SM5703_STATUS2_NOBAT		BIT(4)
#define SM5703_STATUS3_CHGON		BIT(0)
#define SM5703_STATUS3_Q4FULLON		BIT(1)
#define SM5703_STATUS3_TOPOFF		BIT(2)
#define SM5703_STATUS3_DONE		BIT(3)
#define SM5703_STATUS5_VBUSOK		BIT(5)
#define SM5703_STATUS5_VBUSUVLO		BIT(6)
#define SM5703_STATUS5_VBUSOVP		BIT(7)

#define SM5703_VBUSCNTL_LIMIT_MASK	GENMASK(5, 0)
#define SM5703_CHGCNTL2_FASTCHG_MASK	GENMASK(5, 0)
#define SM5703_CHGCNTL3_BATREG_MASK	GENMASK(4, 0)
#define SM5703_CHGCNTL4_TOPOFF_MASK	GENMASK(6, 3)
#define SM5703_CHGCNTL4_AUTOSTOP	BIT(7)
#define SM5703_CHGCNTL5_AICLTH_MASK	GENMASK(2, 0)
#define SM5703_CHGCNTL5_TOPOFF_TIMER_MASK GENMASK(6, 5)
#define SM5703_CHGCNTL5_AICLEN		BIT(7)
#define SM5703_CHGCNTL6_FREQSEL_MASK	GENMASK(3, 2)
#define SM5703_CHGCNTL6_FREQSEL_1P5MHZ	(2 << 2)
#define SM5703_OTGCURRENTCNTL_MASK	GENMASK(1, 0)
#define SM5703_OTGCURRENTCNTL_1P2A	0x03
#define SM5703_Q3LIMITCNTL_1X		BIT(7)

#define SM5703_LDO_ENABLE		BIT(3)
#define SM5703_LDO_VSEL_MASK		GENMASK(2, 0)
#define SM5703_BUCK_ENABLE		BIT(6)
#define SM5703_BUCK_VSEL_MASK		GENMASK(4, 0)

int sm5703_set_charging(struct sm5703 *sm5703, bool enable);
int sm5703_set_otg(struct sm5703 *sm5703, bool enable);
bool sm5703_charging_active(struct sm5703 *sm5703);
bool sm5703_otg_active(struct sm5703 *sm5703);

#endif /* __LINUX_MFD_SM5703_H */
